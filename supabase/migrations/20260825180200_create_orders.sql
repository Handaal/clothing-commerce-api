-- Phase 2D (3/5): canonical Orders & Sales persistence.
--
-- One Order is the sales-domain aggregate shared by POS and ONLINE channels. There is no separate Sale
-- entity. An Order is created directly as `placed` (no draft/cart), belongs to exactly one Tenant, one
-- Brand, and one currency, and carries an immutable commercial snapshot in its order_lines.
--
-- The enforcement boundary mirrors Phase 2B/2C inventory exactly: a dedicated, non-login orders_writer
-- role owns the three tables and the SECURITY DEFINER functions (added in migration 4). service_role
-- (the sole caller) holds no direct table DML; it may only SELECT and EXECUTE the sanctioned functions.
-- Append-only triggers are internal defense-in-depth, never the security boundary.

-- Dedicated, non-login mutation role. It owns orders/order_lines/order_number_sequences and the order
-- functions, so (RLS is never forced) it bypasses RLS on exactly those tables and nothing else. It has
-- no LOGIN, no BYPASSRLS, and is granted to no client or application role, so the only path able to
-- write an Order is through the hardened functions.
do $block$
begin
  if not exists (select 1 from pg_catalog.pg_roles where rolname = 'orders_writer') then
    create role orders_writer nologin noinherit nobypassrls;
  end if;

  -- Transferring ownership to orders_writer (below) requires the migration role to be able to SET ROLE
  -- to it. PostgreSQL 16+ grants the creating role ADMIN but not SET by default, and Supabase applies
  -- migrations as a non-superuser role; without this a fresh `supabase db reset` fails with "must be
  -- able to SET ROLE orders_writer". This is idempotent and never granted to any client or the service
  -- role, preserving the boundary (service_role can never become orders_writer). Superuser test
  -- runners can already SET ROLE, so this is a no-op there.
  execute pg_catalog.format('grant orders_writer to %I with set true', current_user);
end;
$block$;

comment on role orders_writer is
  'Owns the order tables and the SECURITY DEFINER order functions; the sole path able to write orders. Never a login or client role.';

grant usage on schema public to orders_writer;

create schema if not exists orders_private;
revoke all on schema orders_private from public;

comment on schema orders_private is
  'Private order integrity/mutation functions and the idempotency-replay preflight; never a client API surface.';

-- create_order and resolve_idempotent_replay_target run as orders_writer and delegate to the qualified
-- orders_private.order_intent_fingerprint, so the writer role needs USAGE here to resolve that call. It
-- already owns the functions (hence may execute them); this grant only lets it reference the schema.
-- orders_writer remains non-login and is granted to no client or application role, so the boundary is
-- unchanged.
grant usage on schema orders_private to orders_writer;

-- Per-tenant, transactional operational order-number counter. Numbers are generated by locking (or
-- race-safely creating) the tenant row inside create_order and incrementing next_value in the SAME
-- transaction, so a rolled-back create rolls back the increment (no MAX()+1, no burned value on
-- rollback). Numbers are NOT guaranteed gapless and are NOT fiscal/tax invoice numbers.
create table public.order_number_sequences (
  tenant_id uuid primary key,
  next_value bigint not null default 0,
  updated_at timestamptz not null default now(),
  constraint order_number_sequences_tenant_fk
    foreign key (tenant_id) references public.tenants (id) on delete restrict,
  constraint order_number_sequences_next_value_nonnegative check (next_value >= 0)
);

comment on table public.order_number_sequences is
  'Per-tenant transactional order-number counter. Not gapless; the value is an operational number, never a fiscal invoice number.';

-- The canonical Order aggregate root.
create table public.orders (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null,
  brand_id uuid not null,
  branch_id uuid,
  register_id uuid,
  order_number text not null,
  normalized_order_number text generated always as (lower(btrim(order_number))) stored,
  channel text not null,
  status text not null default 'placed',
  currency text not null,
  total_minor bigint not null,
  actor_membership_id uuid,
  idempotency_key text,
  normalized_idempotency_key text generated always as (lower(btrim(idempotency_key))) stored,
  payload_fingerprint text,
  notes text,
  placed_at timestamptz not null default now(),
  cancelled_at timestamptz,
  cancelled_by_membership_id uuid,
  cancellation_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_tenant_fk
    foreign key (tenant_id) references public.tenants (id) on delete restrict,
  constraint orders_brand_tenant_fk
    foreign key (tenant_id, brand_id) references public.brands (tenant_id, id) on delete restrict,
  constraint orders_branch_tenant_fk
    foreign key (tenant_id, branch_id) references public.branches (tenant_id, id) on delete restrict,
  -- A POS order's register must belong to its stored operational branch. MATCH SIMPLE: when branch_id
  -- and register_id are both null (ONLINE), the constraint is not checked.
  constraint orders_register_branch_fk
    foreign key (tenant_id, branch_id, register_id)
    references public.registers (tenant_id, branch_id, id)
    on delete restrict,
  constraint orders_actor_tenant_fk
    foreign key (tenant_id, actor_membership_id)
    references public.memberships (tenant_id, id)
    on delete restrict,
  constraint orders_cancelled_by_tenant_fk
    foreign key (tenant_id, cancelled_by_membership_id)
    references public.memberships (tenant_id, id)
    on delete restrict,
  constraint orders_channel_valid check (channel in ('pos', 'online')),
  constraint orders_status_valid check (status in ('placed', 'cancelled')),
  constraint orders_currency_valid check (currency ~ '^[A-Z]{3}$'),
  constraint orders_total_nonnegative check (total_minor >= 0),
  constraint orders_order_number_not_empty check (normalized_order_number <> ''),
  -- POS carries branch + register (commercial/operational origin, never a fulfillment location).
  -- ONLINE carries neither.
  constraint orders_channel_provenance_consistent check (
    (channel = 'pos' and branch_id is not null and register_id is not null)
    or (channel = 'online' and branch_id is null and register_id is null)
  ),
  constraint orders_idempotency_key_not_blank check (
    idempotency_key is null or normalized_idempotency_key <> ''
  ),
  constraint orders_keyed_has_fingerprint check (
    idempotency_key is null or payload_fingerprint is not null
  ),
  constraint orders_notes_not_empty check (notes is null or btrim(notes) <> ''),
  constraint orders_cancellation_state_consistent check (
    (status = 'cancelled') = (cancelled_at is not null)
  ),
  constraint orders_cancellation_metadata_consistent check (
    cancelled_at is not null or (cancelled_by_membership_id is null and cancellation_reason is null)
  ),
  constraint orders_cancellation_reason_not_empty check (
    cancellation_reason is null or btrim(cancellation_reason) <> ''
  ),
  constraint orders_updated_after_created check (updated_at >= created_at),
  constraint orders_tenant_id_unique unique (tenant_id, id),
  constraint orders_tenant_id_brand_unique unique (tenant_id, id, brand_id),
  constraint orders_tenant_order_number_unique unique (tenant_id, normalized_order_number)
);

comment on table public.orders is
  'Canonical sales-domain aggregate for POS and ONLINE. Immutable after placement except the single placed->cancelled transition. actor_membership_id null means system/online origin.';
comment on column public.orders.branch_id is
  'Commercial/operational origin branch (POS only). NOT a physical fulfillment/inventory location.';
comment on column public.orders.total_minor is
  'Order total in minor units of orders.currency. Equals SUM(order_lines.line_total_minor); computed atomically by create_order.';
comment on column public.orders.payload_fingerprint is
  'Deterministic md5 of the CLIENT-INTENT canonical payload (tenant, channel, currency, register, ordered variant/quantity lines). Excludes resolved prices/snapshots so a retry after a catalog change replays.';

create unique index orders_tenant_idempotency_key_unique_idx
  on public.orders (tenant_id, normalized_idempotency_key)
  where normalized_idempotency_key is not null;

create index orders_tenant_created_idx on public.orders (tenant_id, created_at);
create index orders_tenant_channel_created_idx on public.orders (tenant_id, channel, created_at);
create index orders_tenant_brand_created_idx on public.orders (tenant_id, brand_id, created_at);
create index orders_tenant_branch_created_idx
  on public.orders (tenant_id, branch_id, created_at)
  where branch_id is not null;
create index orders_actor_idx
  on public.orders (tenant_id, actor_membership_id)
  where actor_membership_id is not null;

-- Immutable commercial line snapshot. brand_id and product_id are carried so the single-brand and
-- variant-belongs-to-brand invariants are enforced by composite FKs, no trigger.
create table public.order_lines (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null,
  order_id uuid not null,
  brand_id uuid not null,
  product_id uuid not null,
  variant_id uuid not null,
  line_number integer not null,
  quantity bigint not null,
  unit_price_minor bigint not null,
  line_total_minor bigint not null,
  product_name_snapshot text not null,
  variant_name_snapshot text,
  sku_snapshot text not null,
  option_summary_snapshot text,
  created_at timestamptz not null default now(),
  constraint order_lines_tenant_fk
    foreign key (tenant_id) references public.tenants (id) on delete restrict,
  -- Binds the line to its Order AND forces line.brand_id = order.brand_id (orders.id determines its
  -- brand via the unique (tenant_id, id, brand_id)).
  constraint order_lines_order_brand_tenant_fk
    foreign key (tenant_id, order_id, brand_id)
    references public.orders (tenant_id, id, brand_id)
    on delete restrict,
  -- Product belongs to the line's (and therefore the order's) Brand.
  constraint order_lines_product_brand_tenant_fk
    foreign key (tenant_id, brand_id, product_id)
    references public.products (tenant_id, brand_id, id)
    on delete restrict,
  -- Variant belongs to that Product.
  constraint order_lines_variant_product_tenant_fk
    foreign key (tenant_id, product_id, variant_id)
    references public.product_variants (tenant_id, product_id, id)
    on delete restrict,
  constraint order_lines_line_number_positive check (line_number >= 1),
  constraint order_lines_quantity_positive check (quantity > 0),
  constraint order_lines_unit_price_nonnegative check (unit_price_minor >= 0),
  constraint order_lines_line_total_nonnegative check (line_total_minor >= 0),
  constraint order_lines_line_total_identity check (line_total_minor = quantity * unit_price_minor),
  constraint order_lines_product_name_not_empty check (btrim(product_name_snapshot) <> ''),
  constraint order_lines_variant_name_not_empty check (
    variant_name_snapshot is null or btrim(variant_name_snapshot) <> ''
  ),
  constraint order_lines_sku_not_empty check (btrim(sku_snapshot) <> ''),
  constraint order_lines_option_summary_not_empty check (
    option_summary_snapshot is null or btrim(option_summary_snapshot) <> ''
  ),
  constraint order_lines_tenant_id_unique unique (tenant_id, id),
  constraint order_lines_order_line_number_unique unique (tenant_id, order_id, line_number)
);

comment on table public.order_lines is
  'Immutable commercial snapshot lines. unit_price_minor is the server-authorized charged price at sale time; snapshots survive catalog edits/archival. Duplicate variants on different lines are allowed.';

create index order_lines_variant_idx on public.order_lines (tenant_id, variant_id);

-- Append-only defense-in-depth. Order lines never change after creation. Orders are immutable except
-- the sanctioned placed->cancelled transition, which cancel_order performs after setting the
-- transaction-local allow flag. The real boundary is the privilege model (service_role has no DML);
-- these triggers additionally catch an accidental write by the writer role outside the functions. The
-- GUC is NOT an unforgeable capability and is not the security boundary.
create function orders_private.forbid_order_line_mutation()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $function$
begin
  raise exception using
    errcode = '42501',
    message = 'order_lines are immutable; orders are never edited after placement';
end;
$function$;

create trigger order_lines_append_only
before update or delete on public.order_lines
for each row execute function orders_private.forbid_order_line_mutation();

create function orders_private.guard_order_mutation()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $function$
begin
  if tg_op = 'DELETE' then
    raise exception using
      errcode = '42501',
      message = 'orders cannot be deleted; cancellation is a status transition, never a delete';
  end if;

  -- UPDATE is permitted only for the remainder of a cancel_order call, which sets this flag.
  if pg_catalog.current_setting('orders_private.allow_order_write', true) is distinct from 'on' then
    raise exception using
      errcode = '42501',
      message = 'orders may only be modified through the sanctioned orders_private functions';
  end if;

  return new;
end;
$function$;

create trigger orders_guard
before update or delete on public.orders
for each row execute function orders_private.guard_order_mutation();

-- Transfer ownership so the (migration-4) definer functions write as a role that is not any
-- client/application role, and so that role bypasses (never-forced) RLS on exactly these three tables.
-- ALTER ... OWNER TO additionally requires the new owner to hold CREATE on the object's schema; grant
-- it only for the duration of the transfer and revoke immediately after, so orders_writer keeps just
-- USAGE on public and no standing CREATE anywhere. Supabase applies migrations as a non-superuser role.
grant create on schema public, orders_private to orders_writer;
alter table public.order_number_sequences owner to orders_writer;
alter table public.orders owner to orders_writer;
alter table public.order_lines owner to orders_writer;
alter function orders_private.forbid_order_line_mutation() owner to orders_writer;
alter function orders_private.guard_order_mutation() owner to orders_writer;
revoke create on schema public, orders_private from orders_writer;

-- Deny PUBLIC (and therefore anon/authenticated) execute on the trigger helpers.
revoke all on function orders_private.forbid_order_line_mutation() from public;
revoke all on function orders_private.guard_order_mutation() from public;
